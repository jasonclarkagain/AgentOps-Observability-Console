let seedPromise: Promise<void> | undefined;

async function seedAgentOps(): Promise<void> {
  const existing = await db
    .select({ id: agentRunsTable.id })
    .from(agentRunsTable)
    .where(eq(agentRunsTable.id, seededRuns[0].id))
    .limit(1);

  if (existing.length > 0) {
    return;
  }

  await db.insert(agentRunsTable).values(seededRuns);
  await db.insert(traceEventsTable).values(seededEvents);
  await db.insert(anomaliesTable).values(seededAnomalies);
}

export function ensureAgentOpsSeeded(): Promise<void> {
  if (!seedPromise) {
    seedPromise = seedAgentOps().catch((error: unknown) => {
      seedPromise = undefined;
      throw error;
    });
  }
  return seedPromise;
}